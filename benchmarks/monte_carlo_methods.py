"""Monte Carlo summaries for the task-specific robustcov comparison benchmark.

This script repeats complete synthetic scenarios across independent seeds and
reports medians, interquartile ranges, failure rates, and runtime tails. It
reuses the scenario definitions from ``compare_methods.py`` so documentation
snapshots and repeated validation measure the same tasks.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

import numpy as np

from compare_methods import (
    PROFILES,
    run_graph_benchmarks,
    run_ica_benchmarks,
    run_factor_benchmarks,
    run_kernel_benchmarks,
    run_matrix_benchmarks,
    run_pca_benchmarks,
    run_scatter_benchmarks,
    run_sobi_benchmarks,
    run_tensor_benchmarks,
)

RUNNERS = {
    "scatter": run_scatter_benchmarks,
    "kernel": run_kernel_benchmarks,
    "pca": run_pca_benchmarks,
    "matrix": run_matrix_benchmarks,
    "tensor": run_tensor_benchmarks,
    "graph": run_graph_benchmarks,
    "ica": run_ica_benchmarks,
    "sobi": run_sobi_benchmarks,
    "factor": run_factor_benchmarks,
}

METRICS = [
    "seconds",
    "covariance_error",
    "row_outlier_auc",
    "cell_outlier_auc",
    "subspace_error",
    "missing_reconstruction_mae",
    "matrix_covariance_error",
    "row_mode_subspace_error",
    "column_mode_subspace_error",
    "tensor_reconstruction_mae",
    "precision_error",
    "edge_f1",
    "minimum_distance_index",
    "amari_index",
    "source_correlation",
    "joint_diagonalization_error",
    "factor_subspace_error",
    "factor_score_correlation",
    "common_component_error",
    "factor_covariance_error",
    "factor_count_error",
]


def _numbers(rows, field):
    values = []
    for row in rows:
        try:
            value = float(row.get(field, ""))
        except (TypeError, ValueError):
            continue
        if np.isfinite(value):
            values.append(value)
    return np.asarray(values, dtype=float)


def summarize(rows):
    groups = {}
    for row in rows:
        key = (row["family"], row["scenario"], row["method"])
        groups.setdefault(key, []).append(row)
    output = []
    for (family, scenario, method), group in sorted(groups.items()):
        ok = [row for row in group if row.get("status") == "ok"]
        item = {
            "family": family,
            "scenario": scenario,
            "method": method,
            "n_runs": len(group),
            "n_success": len(ok),
            "failure_rate": 1.0 - len(ok) / max(len(group), 1),
        }
        for metric in METRICS:
            values = _numbers(ok, metric)
            item[f"{metric}_median"] = float(np.median(values)) if values.size else ""
            item[f"{metric}_q25"] = float(np.quantile(values, 0.25)) if values.size else ""
            item[f"{metric}_q75"] = float(np.quantile(values, 0.75)) if values.size else ""
            if metric == "seconds":
                item["seconds_p95"] = float(np.quantile(values, 0.95)) if values.size else ""
        output.append(item)
    return output


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = list(rows[0]) if rows else ["family", "scenario", "method"]
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def write_rst(path, rows, seeds, profile):
    lines = [
        ".. Generated by benchmarks/monte_carlo_methods.py.",
        "",
        "Monte Carlo benchmark summary",
        "-----------------------------",
        "",
        f"Profile: ``{profile}``. Independent scenario seeds: {seeds[0]} through {seeds[-1]}.",
        "Values are medians with interquartile ranges. Failure rate includes numerical and convergence exceptions.",
        "",
    ]
    for family in sorted({row["family"] for row in rows}):
        lines.extend([family.title(), "~" * len(family), "", ".. list-table::", "   :header-rows: 1", "", "   * - Scenario", "     - Method", "     - Main metric", "     - Runtime median [IQR]", "     - Failure rate"])
        family_rows = [row for row in rows if row["family"] == family]
        preferred = {
            "scatter": "covariance_error",
            "kernel outlier detection": "row_outlier_auc",
            "pca": "subspace_error",
            "matrix covariance": "matrix_covariance_error",
            "multilinear pca": "tensor_reconstruction_mae",
            "sparse precision": "edge_f1",
            "ica": "minimum_distance_index",
            "sobi": "minimum_distance_index",
            "factor model": "factor_subspace_error",
        }.get(family, "seconds")
        for row in family_rows:
            def fmt(name):
                value = row.get(name, "")
                return "—" if value == "" else f"{float(value):.3f}"
            main = f"{preferred}: {fmt(preferred + '_median')} [{fmt(preferred + '_q25')}, {fmt(preferred + '_q75')}]"
            runtime = f"{fmt('seconds_median')} [{fmt('seconds_q25')}, {fmt('seconds_q75')}]"
            lines.extend([
                f"   * - {row['scenario']}",
                f"     - {row['method']}",
                f"     - {main}",
                f"     - {runtime}",
                f"     - {100.0 * float(row['failure_rate']):.1f}%",
            ])
        lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", choices=sorted(PROFILES), default="quick")
    parser.add_argument("--families", nargs="+", choices=sorted(RUNNERS), default=["scatter", "pca", "tensor"])
    parser.add_argument("--seed-start", type=int, default=0)
    parser.add_argument("--n-seeds", type=int, default=20)
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument("--rst", type=Path, default=None)
    args = parser.parse_args()
    if args.n_seeds < 1:
        raise ValueError("n-seeds must be positive")
    seeds = list(range(args.seed_start, args.seed_start + args.n_seeds))
    rows = []
    for seed in seeds:
        for family in args.families:
            rows.extend(RUNNERS[family](PROFILES[args.profile], 1, seed))
    summary = summarize(rows)
    write_csv(args.csv, summary)
    if args.rst:
        write_rst(args.rst, summary, seeds, args.profile)
    print(f"completed {len(rows)} fits across {len(seeds)} seeds; {sum(row['status'] != 'ok' for row in rows)} failures")


if __name__ == "__main__":
    main()
